-- Создаём только недостающую таблицу и заполняем её

CREATE TABLE IF NOT EXISTS "расчет_температуры_таблица_1" (
    "id"                    INTEGER       NOT NULL,
    "код"                   VARCHAR(20)   NOT NULL,
    "высота_м"              INTEGER       NOT NULL,
    "температура_цельсия"   NUMERIC(5,2)  NOT NULL,
    PRIMARY KEY ("id"),
    UNIQUE ("код"),
    CHECK ("высота_м" >= 0)
);

-- Расчёт температуры по стандартной атмосфере:
-- t = 15 - 0.0065 * высота (15 °C на уровне моря, падение 6.5 °C на 1 км)
INSERT INTO "расчет_температуры_таблица_1" ("id", "код", "высота_м", "температура_цельсия")
SELECT v.id, 'TMP-' || LPAD(CAST(v.id AS VARCHAR), 3, '0'), v.h, v.t
FROM (VALUES
    (1, 0, 15.00),    (2, 500, 11.75),   (3, 1000, 8.50),   (4, 1500, 5.25),
    (5, 2000, 2.00),  (6, 3000, -4.50),  (7, 4000, -11.00), (8, 5000, -17.50),
    (9, 6000, -24.00),(10, 8000, -37.00),(11, 10000, -50.00)
) AS v(id, h, t)
WHERE NOT EXISTS (SELECT 1 FROM "расчет_температуры_таблица_1" x WHERE x.id = v.id);
